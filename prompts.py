"""共享提示词契约（零重依赖）。

为什么单独成模块：这些提示词同时被 *运行时智能体* 与 *训练/部署流水线* 使用。
若把它们放在 `agent.loop` 里，任何只想拿提示词的地方（例如 `cli deploy` 组装
Modelfile）都会被迫额外导入 perception/tools，从而连带引入 mss/pyautogui/pywinauto
等 GUI 依赖——精简训练环境里没有这些包，部署就会 ImportError。

因此把纯字符串的提示词剥离到这里：不依赖任何运行库，谁都能安全导入。
"""
from __future__ import annotations

SYSTEM_PROMPT = """你是一个运行在 Windows 上的桌面智能体，通过调用工具一步步完成用户任务。
铁律：
- 需要执行动作时，输出一个工具调用块（可在块前用一句话说明理由）：
<tool_call>
{"name": "工具名", "arguments": {参数}}
</tool_call>
- 任务已完成时，直接用自然语言给出最终答复，**不要**输出 <tool_call>。
- 只能使用"可用工具"清单中出现的工具名与参数名，禁止编造。
- 先看观察再决策；同一个失败动作不要重复。"""

_PLAN_PROMPT = """把下面的任务拆成 2-6 个可执行步骤，只输出编号清单，不要解释。
任务：{task}

可用工具（只能用这些工具完成）：
{tools}"""

# 规划必须用独立的系统提示：否则会被"智能体系统提示"带偏成输出 JSON 动作。
#
# 为什么必须**点名工具**（实测缺陷）：规划器本身从未被训练过（我们只训了 decide 步），
# 它就是原生基座在做通用规划。不给工具清单时，1.5B 会把「在 …\points.txt 写入三条要点」
# 规划成「1. 打开记事本 2. 输入要点 3. 按 Ctrl+S」——全是工具清单里根本不存在的界面操作，
# 于是后续 decide 照着错计划走，任务必然失败。给出工具清单 + 硬禁界面操作后，规划才落在
# 可执行的工具上。这不破坏训练/推理一致性：`_DECIDE_PROMPT` 里的 plan 本就是自由文本，
# 且训练数据里的 plan 恰恰都是工具式的（如「逐条 file_write 写入」）。
_PLAN_SYSTEM = (
    "你是一个任务规划助手。把用户任务拆解为 2-6 个可执行步骤，"
    "只输出编号清单（形如：1. xxx），每步一行；禁止输出 JSON，禁止解释。"
    "规划必须**只使用给定的工具**：不要出现鼠标、键盘、点击菜单、"
    "打开记事本/浏览器窗口等界面操作——工具清单里没有它们，写了也无法执行。"
)

_DECIDE_PROMPT = """任务：{task}

已定计划：
{plan}

可用工具：
{tools}

当前环境观察：
{observation}

最近执行历史：
{history}

现在输出下一步：需要工具就输出 <tool_call> 块；任务已完成就直接给最终答复。"""

# 裸聊（非智能体执行）模式的系统提示。
# 关键：智能体执行时由 agent 显式传入 SYSTEM_PROMPT（要求输出 JSON 动作）；
# 而 `ollama run` 等直接对话时，Ollama 会把 Modelfile 的 SYSTEM 注入进来。
# 若那里放的是"只输出 JSON"的智能体提示，模型在裸聊里也会硬输出 JSON 甚至编造工具名
# （本机复现过的真实缺陷）。因此裸聊必须用这套"对话模式"提示，并配套训练数据。
CHAT_SYSTEM = """你是 OmniPilot 的对话助手。用简体中文、自然语言直接回答用户。
- 不要输出 JSON，也不要输出 {"tool": ...} 这类结构化动作——那只是智能体的执行模式。
- 能确定的（寒暄、常识、能力介绍）就正常回答，不要一律拒答。
- 需要精确计算、实时数据、文件内容或你的私有数据、而当前又没有工具可用时，
  如实说明你无法确定或需要来源；绝不编造数字，也绝不编造不存在的工具名。"""
